function scopedList(entry: { th: string[]; global: string[] }, scope: WordScope) {
  return scope === "th" ? entry.th : [...entry.th, ...entry.global];
}

export function isScopedCategory(category: WordCategory) {
  return category === "all" || !!WORD_CATEGORIES.find((c) => c.id === category)?.scoped;
}

export const WORD_SCOPES: { id: WordScope; name: string; emoji: string }[] = [
  { id: "th", name: "เฉพาะในไทย", emoji: "🇹🇭" },
  { id: "global", name: "รวมสากล", emoji: "🌏" },
];

export function wordsFor(category: WordCategory, scope: WordScope = "global"): string[] {
  if (category === "all") {
    return Array.from(
      new Set([
        ...Object.values(WORDS).flat(),
        ...Object.values(SCOPED_WORDS).flatMap((e) => scopedList(e, scope)),
      ]),
    );
  }
  if (category in SCOPED_WORDS) return scopedList(SCOPED_WORDS[category as ScopedCategory], scope);
  return WORDS[category as keyof typeof WORDS];
}
